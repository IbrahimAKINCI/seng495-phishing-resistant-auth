"""FR-A5: passkey registration and login.

The 11 checks from Section 4.2 of the requirements, and where each one happens:

 1. challenge was generated by our server      -> stored in the challenges table, passed as expected_challenge
 2. challenge not used before                  -> consume_challenge() marks it used before verifying
 3. challenge not expired (5 minutes)          -> consume_challenge()
 4. clientDataJSON type is create/get          -> py_webauthn
 5. origin matches                             -> py_webauthn (expected_origin)
 6. RP ID hash matches                         -> py_webauthn (expected_rp_id)
 7. user presence (UP) flag set                -> py_webauthn
 8. user verification (UV) when policy says so -> py_webauthn (require_user_verification)
 9. signature valid                            -> py_webauthn
10. signature counter did not go backwards     -> py_webauthn (credential_current_sign_count)
11. credential belongs to the user /
    not registered twice                       -> find_login_passkey() / register_verify()

Each check has a negative test in tests/test_webauthn.py."""
import json
import secrets

from sqlalchemy import select
from sqlalchemy.orm import Session
from webauthn import (
    base64url_to_bytes,
    generate_authentication_options,
    generate_registration_options,
    options_to_json,
    verify_authentication_response,
    verify_registration_response,
)
from webauthn.helpers.exceptions import InvalidAuthenticationResponse, InvalidRegistrationResponse
from webauthn.helpers.structs import (
    AuthenticatorSelectionCriteria,
    PublicKeyCredentialDescriptor,
    ResidentKeyRequirement,
    UserVerificationRequirement,
)

from . import config
from .clock import clock
from .errors import AuthError, login_failed
from .models import Challenge, Passkey, User

REGISTRATION_FAILED = "Passkey registration failed."


def _new_challenge(db: Session, ceremony: str, user_id: int | None) -> Challenge:
    ch = Challenge(
        id=secrets.token_urlsafe(32),
        ceremony=ceremony,
        user_id=user_id,
        challenge=secrets.token_bytes(32),
        expires_at=clock.now() + config.CHALLENGE_TTL_SECONDS,
        used=False,
    )
    db.add(ch)
    db.commit()
    return ch


def consume_challenge(db: Session, challenge_id: str, ceremony: str) -> Challenge | None:
    """Checks 1-3. The challenge is marked used before the response is verified,
    so even a failed attempt cannot be retried with the same challenge."""
    ch = db.get(Challenge, challenge_id)
    if ch is None or ch.ceremony != ceremony:
        return None  # check 1: not a challenge we issued for this ceremony
    if ch.used:
        return None  # check 2
    ch.used = True
    db.commit()
    if clock.now() > ch.expires_at:
        return None  # check 3
    return ch


def _uv_requirement(require_uv: bool) -> UserVerificationRequirement:
    return UserVerificationRequirement.REQUIRED if require_uv else UserVerificationRequirement.PREFERRED


def _credential_raw_id(credential: dict) -> bytes | None:
    try:
        return base64url_to_bytes(credential["rawId"])
    except (KeyError, TypeError, ValueError):
        return None


# ---------- registration ----------

def register_options(db: Session, user: User, require_uv: bool) -> tuple[dict, str]:
    ch = _new_challenge(db, "registration", user.id)
    options = generate_registration_options(
        rp_id=config.RP_ID,
        rp_name=config.RP_NAME,
        user_name=user.username,
        user_id=user.webauthn_user_handle,
        challenge=ch.challenge,
        authenticator_selection=AuthenticatorSelectionCriteria(
            resident_key=ResidentKeyRequirement.PREFERRED,
            user_verification=_uv_requirement(require_uv),
        ),
        exclude_credentials=[PublicKeyCredentialDescriptor(id=p.credential_id) for p in user.passkeys],
    )
    return json.loads(options_to_json(options)), ch.id


def register_verify(db: Session, user: User, challenge_id: str, credential: dict, name: str, require_uv: bool) -> Passkey:
    ch = consume_challenge(db, challenge_id, "registration")
    if ch is None or ch.user_id != user.id:
        raise AuthError(400, REGISTRATION_FAILED)

    raw_id = _credential_raw_id(credential)
    if raw_id is None:
        raise AuthError(400, REGISTRATION_FAILED)
    if db.scalar(select(Passkey).where(Passkey.credential_id == raw_id)) is not None:
        raise AuthError(400, REGISTRATION_FAILED)  # check 11: already registered

    try:
        verified = verify_registration_response(
            credential=credential,
            expected_challenge=ch.challenge,
            expected_rp_id=config.RP_ID,
            expected_origin=config.EXPECTED_ORIGIN,
            require_user_verification=require_uv,
        )
    except (InvalidRegistrationResponse, ValueError, KeyError, TypeError):
        raise AuthError(400, REGISTRATION_FAILED)

    passkey = Passkey(
        user_id=user.id,
        credential_id=verified.credential_id,
        public_key=verified.credential_public_key,
        sign_count=verified.sign_count,
        name=(name or "Passkey")[:64],
        aaguid=str(verified.aaguid),
        created_at=clock.now(),
    )
    db.add(passkey)
    db.commit()
    return passkey


# ---------- login ----------

def login_options(db: Session, user: User | None, require_uv: bool) -> tuple[dict, str]:
    """With a username the browser is told which passkeys to offer. Without one
    (usernameless login) the browser offers any passkey stored for our RP ID."""
    ch = _new_challenge(db, "authentication", user.id if user else None)
    allow = [PublicKeyCredentialDescriptor(id=p.credential_id) for p in user.passkeys] if user else None
    options = generate_authentication_options(
        rp_id=config.RP_ID,
        challenge=ch.challenge,
        allow_credentials=allow,
        user_verification=_uv_requirement(require_uv),
    )
    return json.loads(options_to_json(options)), ch.id


def find_login_passkey(db: Session, ch: Challenge, credential: dict) -> Passkey | None:
    """Check 11: the credential must exist and, if the challenge was issued for a
    specific user, belong to that user."""
    raw_id = _credential_raw_id(credential)
    if raw_id is None:
        return None
    passkey = db.scalar(select(Passkey).where(Passkey.credential_id == raw_id))
    if passkey is None:
        return None
    if ch.user_id is not None and passkey.user_id != ch.user_id:
        return None
    return passkey


def login_verify(db: Session, challenge_id: str, credential: dict, require_uv: bool) -> tuple[Passkey, bool]:
    ch = consume_challenge(db, challenge_id, "authentication")
    if ch is None:
        raise login_failed()
    passkey = find_login_passkey(db, ch, credential)
    if passkey is None:
        raise login_failed()
    try:
        verified = verify_authentication_response(
            credential=credential,
            expected_challenge=ch.challenge,
            expected_rp_id=config.RP_ID,
            expected_origin=config.EXPECTED_ORIGIN,
            credential_public_key=passkey.public_key,
            credential_current_sign_count=passkey.sign_count,
            require_user_verification=require_uv,
        )
    except (InvalidAuthenticationResponse, ValueError, KeyError, TypeError):
        raise login_failed()

    passkey.sign_count = verified.new_sign_count
    passkey.last_used_at = clock.now()
    db.commit()
    return passkey, verified.user_verified
