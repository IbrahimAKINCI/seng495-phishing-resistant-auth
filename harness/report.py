"""Builds the attack results table from results/attack_results.jsonl.

    python -m harness.report                 writes docs/results_attacks.md
    python -m harness.report IN.jsonl OUT.md

The table is produced by this script and never edited by hand. For each attack and
method the latest recorded result is used. The header lists the commit and the machine
the results came from, so a reader can reproduce them (NFR-5)."""
import sys
from pathlib import Path

from . import logs, results

DEFAULT_OUT = Path("docs/results_attacks.md")


def latest_per_pair(rows: list[dict]) -> list[dict]:
    """Latest row for each (attack, method), in the order the pairs first appeared."""
    latest: dict[tuple[str, str], dict] = {}
    for row in rows:
        key = (row["attack"], row["method"])
        if key not in latest or row["time"] >= latest[key]["time"]:
            latest[key] = row
    return list(latest.values())


def build_table(rows: list[dict]) -> str:
    if not rows:
        raise ValueError("no attack results to report")
    used = latest_per_pair(rows)
    commits = sorted({r["commit"][:7] for r in used})
    machines = sorted({r["machine"]["os"] + ", " + str(r["machine"]["cpu_count"]) + " CPUs, Python "
                       + r["machine"]["python"] for r in used})
    lines = [
        "# Attack results",
        "",
        "Generated by `python -m harness.report` from `results/attack_results.jsonl`. Do not edit by hand.",
        "",
        f"- Commit: {', '.join(commits)}",
        f"- Machine: {'; '.join(machines)}",
        f"- Results from: {min(r['time'] for r in used)} to {max(r['time'] for r in used)}",
        "",
        "| Attack | Method | Expected | Actual | Expectation confirmed | Detail |",
        "|---|---|---|---|---|---|",
    ]
    for r in used:
        mark = "yes" if r["confirmed"] else "**NO (finding)**"
        detail = r.get("detail", "").replace("|", "/")
        lines.append(f"| {r['attack']} | {r['method']} | {r['expected']} | {r['actual']} | {mark} | {detail} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    source = Path(argv[1]) if len(argv) > 1 else results.RESULTS_DIR / results.ATTACK_FILE
    target = Path(argv[2]) if len(argv) > 2 else DEFAULT_OUT
    rows = logs.read_jsonl(source)
    if not rows:
        print(f"No results in {source}. Run `pytest attacks` first.")
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(build_table(rows), encoding="utf-8")
    print(f"Wrote {target} ({len(latest_per_pair(rows))} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
