"""T-A5 and T-A5.1 to T-A5.11: passkey registration, login and the 11 checks in
Section 4.2. Each negative test breaks exactly one thing and expects a rejection."""
import os

from app.auth import config
from app.auth.clock import clock

from .conftest import add_passkey, as_user, passkey_options, passkey_verify, register, use_policy
from .soft_authenticator import b64u


# ---------- T-A5: valid ceremonies ----------

def test_register_and_log_in_with_username(client, authenticator):
    uid = register(client)
    add_passkey(client, authenticator, uid)
    opts = passkey_options(client, "alice")
    r = passkey_verify(client, opts["challenge_id"], authenticator.get(opts["options"]))
    assert r.status_code == 200, r.text
    assert r.json()["methods"] == ["passkey"]
    assert r.json()["user_id"] == uid


def test_usernameless_login(client, authenticator):
    uid = register(client)
    add_passkey(client, authenticator, uid)
    opts = passkey_options(client)
    assert "allowCredentials" not in opts["options"] or not opts["options"]["allowCredentials"]
    r = passkey_verify(client, opts["challenge_id"], authenticator.get(opts["options"]))
    assert r.status_code == 200 and r.json()["user_id"] == uid


def test_unknown_username_gets_usernameless_options(client):
    opts = passkey_options(client, "nobody")
    assert not opts["options"].get("allowCredentials")


