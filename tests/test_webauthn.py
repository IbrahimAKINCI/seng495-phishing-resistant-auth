# ---------- T-A5.11: credential belongs to the user / not registered twice ----------

def test_11_other_users_credential_is_rejected(client, authenticator):
    alice = register(client, "alice")
    bob = register(client, "bob")
    add_passkey(client, authenticator, alice)
    _, bob_cred = add_passkey(client, authenticator, bob)
    opts = passkey_options(client, "alice")  # challenge issued for alice
    r = passkey_verify(client, opts["challenge_id"], authenticator.get(opts["options"], bob_cred))
    assert r.status_code == 401


def test_11_unknown_credential_is_rejected(client, authenticator):
    uid = register(client)
    add_passkey(client, authenticator, uid)
    other = type(authenticator)()
    other_uid = register(client, "carol")
    _, cred = add_passkey(client, other, other_uid)
    client.delete("/auth/credentials/password", headers=as_user(other_uid))  # carol keeps the passkey only
    from app.auth.db import SessionLocal
    from app.auth.models import Passkey
    with SessionLocal() as db:  # remove carol's passkey from the server, keep it in the authenticator
        db.query(Passkey).filter(Passkey.user_id == other_uid).delete()
        db.commit()
    opts = passkey_options(client)
    assert passkey_verify(client, opts["challenge_id"], other.get(opts["options"], cred)).status_code == 401


def test_11_same_credential_cannot_be_registered_twice(client, authenticator):
    alice = register(client, "alice")
    bob = register(client, "bob")
    _, cred = add_passkey(client, authenticator, alice)
    for uid in (alice, bob):
        body = client.post("/auth/webauthn/register/options", headers=as_user(uid)).json()
        again = authenticator.create(body["options"], reuse=cred)  # fresh, valid response for the same key
        r = client.post("/auth/webauthn/register/verify", json={"challenge_id": body["challenge_id"], "credential": again}, headers=as_user(uid))
        assert r.status_code == 400


